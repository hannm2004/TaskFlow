import java.util.ArrayList;
import java.util.List;

/**
 *
 * @author HP
 */
public class GenericRepository<T extends Task> {

    private List<T> items = new ArrayList<>();

    public void add(T item) {
        items.add(item);
    }

    public List<T> getAll() {
        return items;
    }
}
